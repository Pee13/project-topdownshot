namespace TopDownTacticalAI.Core
{
    /// <summary>
    /// บทบาทสำเร็จรูปของศัตรูแต่ละตัว ปรับพารามิเตอร์หลายตัวพร้อมกันให้เข้ากับบุคลิกนั้นๆ
    /// เลือกใน Inspector ของ EnemyBrain แล้วระบบจะปรับค่าที่เกี่ยวข้องให้อัตโนมัติตอนเริ่มเกม
    /// เลือก Custom ถ้าอยากตั้งค่าทุกอย่างเองแบบละเอียดโดยไม่ให้ระบบ Role มาเปลี่ยนทับ
    /// </summary>
    public enum EnemyRole
    {
        Custom,     // ไม่ปรับอะไร ใช้ค่าที่ตั้งเองใน Inspector ทั้งหมด
        Aggressive, // บุกใกล้ ไม่ค่อยถอย ไล่เร็ว เหมาะเป็นตัวหลักบุกนำ
        Defensive,  // รักษาระยะ หลบเข้าที่กำบังไว ยิงจากที่ไกล เหมาะเป็นตัวคุ้มกัน
        Sniper,     // ยิงจากระยะไกลมาก ไม่เข้าใกล้ ไล่ตามช้า เหมาะเป็นตัวคุมพื้นที่
        Scout       // มองไกล ได้ยินไกล ลาดตระเวนพื้นที่กว้าง เหมาะเป็นตัวแจ้งเตือน/หาตัวก่อน
    }
}
